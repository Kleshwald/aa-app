import { faker } from './seed';

/**
 * Канонический номер полиса ОСАГО — ЕДИНЫЙ формат во всём прототипе:
 * серия «ХХХ» + пробел + 10 цифр (как на реальном бланке и е-полисе).
 *
 * Один источник специально, чтобы «Мои клиенты», «Пролонгация» и страница
 * договора не расходились в написании номера (фидбэк агента с доски 2026-07-07:
 * где-то «ХХХ 1234567890», где-то слитно — «лучше один подход»).
 */
export function osagoPolicyNumber(): string {
  return `ХХХ ${faker.string.numeric(10)}`;
}
